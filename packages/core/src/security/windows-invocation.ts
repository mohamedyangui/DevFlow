import { DevflowError, ErrorCode } from "../errors.js";

/**
 * Pure helpers for running Windows batch files safely (ADR 0014, ADR 0018). They have no side
 * effects and are unit-tested on every platform.
 */

/**
 * Characters that `cmd.exe` interprets even inside quotes, or that would end a quoted argument:
 * variable expansion (`%`, `!`), escapes (`^`), command separators and redirections (`&`, `|`,
 * `<`, `>`), grouping (`(`, `)`), quotes and every control character including CR and LF.
 * Arguments containing one are rejected, never escaped.
 */
// eslint-disable-next-line no-control-regex
const FORBIDDEN_BATCH_ARGUMENT = /[%!^&|<>"()\u0000-\u001f\u007f]/;
// eslint-disable-next-line no-control-regex
const FORBIDDEN_BATCH_PATH = /[%!^"\u0000-\u001f\u007f]/;
/** Characters `cmd.exe` treats as argument delimiters; such arguments are quoted. */
const NEEDS_QUOTES = /[ \t,;=]/;

/** Throws `COMMAND_ARGUMENT_REJECTED` when an argument cannot be passed to a batch file. */
export function checkBatchArgument(argument: string, index: number): void {
  const forbidden = FORBIDDEN_BATCH_ARGUMENT.exec(argument);
  if (forbidden !== null) {
    const character = forbidden[0];
    const code = character.charCodeAt(0);
    const shown =
      code < 0x20 || code === 0x7f
        ? `U+${code.toString(16).toUpperCase().padStart(4, "0")}`
        : `"${character}"`;
    throw new DevflowError(
      ErrorCode.CommandArgumentRejected,
      `argument ${index + 1} contains ${shown}, which cannot be passed safely to a Windows batch file; ` +
        "use a command that does not need cmd.exe (a direct executable, a Node script or the Java launcher)",
      { details: { index, character: shown } },
    );
  }
  if (argument.endsWith("\\") && NEEDS_QUOTES.test(argument)) {
    throw new DevflowError(
      ErrorCode.CommandArgumentRejected,
      `argument ${index + 1} ends with a backslash and needs quotes, which would escape the closing quote`,
      { details: { index, character: '"\\"' } },
    );
  }
}

/**
 * Builds the text after `cmd.exe /d /s /v:off /c`: the quoted batch file followed by its
 * arguments, each quoted when it contains a delimiter. The caller wraps the result in one more
 * pair of quotes, which `/s` strips.
 */
export function batchCommandLine(batchFile: string, args: readonly string[]): string {
  if (FORBIDDEN_BATCH_PATH.test(batchFile)) {
    throw new DevflowError(
      ErrorCode.CommandArgumentRejected,
      `the batch file path ${JSON.stringify(batchFile)} contains characters cmd.exe would interpret`,
      { details: { path: batchFile } },
    );
  }
  args.forEach((arg, index) => {
    checkBatchArgument(arg, index);
  });
  const quoted = args.map((arg) => (arg === "" || NEEDS_QUOTES.test(arg) ? `"${arg}"` : arg));
  return [`"${batchFile}"`, ...quoted].join(" ");
}

/** The fixed `cmd.exe` argument layout of the `windows-batch` strategy. */
export function cmdArguments(batchFile: string, args: readonly string[]): string[] {
  return ["/d", "/s", "/v:off", "/c", `"${batchCommandLine(batchFile, args)}"`];
}

/**
 * Finds the JavaScript entry point that a Node.js command shim runs: the shims generated by
 * npm and pnpm for `node_modules/.bin`, and the `npm.cmd`/`pnpm.cmd` shims of a Node.js
 * installation. Returns the path as written in the shim, relative to the shim's directory, or
 * `undefined` when the file is not a recognizable shim.
 */
export function shimEntryPoint(shimText: string): string | undefined {
  const pattern = /(?:%~dp0|%dp0%)\\*([^"%\r\n*?<>|]{1,512}?\.[cm]?js)"/gi;
  let last: string | undefined;
  for (const match of shimText.matchAll(pattern)) last = match[1];
  return last;
}

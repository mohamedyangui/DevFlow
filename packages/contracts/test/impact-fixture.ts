const CONTROLLER = `package com.shop.orders;

import org.springframework.web.bind.annotation.*;

@RestController
@RequestMapping("/api/orders")
public class OrderController {

    @GetMapping
    public List<Order> listOrders() { return service.list(); }

    @GetMapping("/{id}")
    public Order getOrder(@PathVariable String id) { return service.get(id); }

    @DeleteMapping(value = "/{orderId}")
    public void deleteOrder(@PathVariable String orderId) { service.delete(orderId); }

    // @DeleteMapping("/{id}") in a comment is not a mapping
    @RequestMapping(path = "/{id}/archive", method = RequestMethod.POST)
    public void archive(@PathVariable String id) {}
}

@RestController
class CustomerController {
    @DeleteMapping("/api/customers/{id}")
    public void delete(@PathVariable String id) {}
}
`;

const GRPC_SERVICE = `package com.shop.orders;

import com.shop.orders.v1.OrderServiceGrpc;
import com.shop.orders.v1.OrdersProto.Order;

public class OrderGrpcService extends OrderServiceGrpc.OrderServiceImplBase {
    public void getOrder(Order request, StreamObserver<Order> responses) {
        responses.onNext(Order.newBuilder().setId(request.getId()).build());
    }
}
`;


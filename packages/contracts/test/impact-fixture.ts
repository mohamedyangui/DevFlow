const TS_CLIENT = `import axios from "axios";
import { Order } from "../gen/shop/v1/orders_pb";
import { ordersApi } from "./generated-client";

const API_BASE = process.env.API_BASE ?? "";

export async function loadOrder(id: string): Promise<Order> {
  const response = await fetch(\`\${API_BASE}/orders/\${id}\`);
  return Order.fromJson(await response.json());
}

export function removeOrder(id: string) {
  return axios.delete("/api/orders/" + id);
}

export function removeOrderGenerated(id: string) {
  return ordersApi.deleteOrder({ id });
}

export function customers() {
  // fetch("/api/orders/1", { method: "DELETE" }) in a comment is not a call
  return fetch("/api/customers");
}
`;


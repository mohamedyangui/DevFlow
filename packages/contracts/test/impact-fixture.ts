/**
 * A mini repository for change impact (ADR 0022), made up for the tests: one OpenAPI document
 * and one `.proto` file, consumed by a Spring controller, a Java gRPC service, a TypeScript
 * client, a Python module, and their tests. The files are strings so that the TypeScript
 * client (which imports `axios`) is not type-checked or linted as part of the repository;
 * the review-mode test writes them to a temporary workspace.
 *
 * The head versions remove `DELETE /orders/{id}` and the field `Order.total` (not reserved):
 * both are breaking.
 */

